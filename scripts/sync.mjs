#!/usr/bin/env node
/**
 * scripts/sync.mjs -- one-command dev sync for starci-academy-backend.
 *
 * Cross-platform (Windows, macOS, Linux/CI), node builtins only, no
 * dependencies -- so it runs before `npm ci` and before anything is built.
 *
 *   npm run sync                        decrypt, generate the env bridge, sync gitmounts
 *   npm run sync -- --out <path>        write the env bridge somewhere harmless
 *   npm run sync -- --write-override    force-write the live .env.override (CUTOVER)
 *   npm run sync -- --quiet             near-silent, never fatal (the prestart hook)
 *   npm run sync -- --help              this text
 *
 * What it does, in order:
 *   1. read metadata.json                 (single source of truth for every port)
 *   2. locate the shared master age key   (~/.starci/master.identity)
 *   3. check `sops` + `age` are on PATH
 *   4. sops-decrypt every .stacks/dev/**\/*.enc to the plaintext twin beside it
 *   5. GENERATE the env bridge            <-- the step that makes a fresh box boot
 *   6. clone/pull every gitmount declared in metadata.json, using an encrypted
 *      runtime credential when the mount declares one
 *   7. create empty placeholders for the mount files boot would ENOENT on
 *   8. cross-check .stacks/dev/runtime/env/KEYS.md against what was produced
 *   9. print the resolved ports and the next commands
 *
 * Why step 5 matters: `src/modules/platform/env/config.ts` defaults point at
 * STANDARD ports (postgres 5432, redis 6379, qdrant 6333) and at the legacy
 * `.mount/` tree, while the compose fragments publish OFFSET ports and the
 * credentials now live under `.stacks/dev/runtime`. The generated override is
 * the bridge. It is gitignored and nothing ships it, so without this script a
 * fresh clone boots straight into ECONNREFUSED (or ENOENT).
 *
 * WHERE IT WRITES -- read this before running it on a live machine:
 *   - `.env.override` does not exist            -> writes `.env.override` (fresh clone)
 *   - `.env.override` starts with our marker    -> rewrites `.env.override` (already ours)
 *   - `.env.override` is hand-written / legacy  -> writes `.env.override.generated`
 *                                                  and does NOT touch the live file
 * That last case is today's state: the running backend keeps its working file
 * until the operator promotes the preview deliberately (see PROMOTION below).
 *
 * PROMOTION (the cutover, done once, by a human or the orchestrator):
 *   1. npm run sync                      -> writes .env.override.generated
 *   2. diff it against .env.override BY KEY NAME and eyeball the result
 *   3. stop the old stack, bring the new one up (npm run compose)
 *   4. npm run sync -- --write-override  -> backs the old file up to
 *                                           .env.override.bak, then writes the real one
 *   5. boot, verify, then delete the .bak (it still holds plaintext credentials)
 *
 * Every credential -- infra password and third-party key alike -- is written as
 * a `<KEY>_FILE` pointer, never as a value: config.ts reads each of them through
 * `parseEnvSecret`, which opens the file itself. The env bridge therefore holds
 * paths and ports, and no secret survives in it.
 *
 * This script NEVER prints a secret value. It prints key NAMES and ports only.
 */

