// step 9 -- summary
// ---------------------------------------------------------------------------

/**
 * Prints the resolved ports and the commands to run next. Infra is deliberately
 * NOT started here -- `npm run compose` owns that.
 * @param ports - resolved port map.
 * @param target - `{ path, mode }` the env bridge was written to.
 */
const printSummary = (ports, target) => {
    step("summary")
    const width = Math.max(...Object.keys(ports).map((name) => name.length))
    for (const [name, port] of Object.entries(ports)) {
        info(`${name.padEnd(width)}  ${port}`)
    }
    console.log(`\n    ${green("core")}  http://localhost:${ports.core}`)
    console.log(`    ${dim("resolved ports: metadata.json; allocation: Source .workspace/ports/starci-academy.json")}`)
    console.log(`\n    ${cyan("next:")}`)
    console.log("      npm ci")
    console.log("      npm run compose")
    if (target.mode === "preview") {
        console.log("      # then, once the new stack is verified:")
        console.log("      npm run sync -- --write-override")
    }
    console.log("      npm run start:dev\n")
}

// ---------------------------------------------------------------------------
// entrypoint
// ---------------------------------------------------------------------------

const HELP = `
starci-academy-backend dev sync

  npm run sync                     decrypt secrets, generate the env bridge, sync gitmounts
  npm run sync -- --out <path>     write the env bridge to <path> instead
  npm run sync -- --write-override force-write the live .env.override (cutover only)
  npm run sync -- --quiet          near-silent, never fatal (used by the prestart hooks)
  npm run sync -- --help           this text

By default the live .env.override is only written when it does not exist yet, or
when it already carries this script's header. A hand-written one is left alone
and the run produces .env.override.generated instead -- diff that, then promote.

Ports come from metadata.json. Secrets come from the shared master age key at
${MASTER_KEY_PATH} -- never from the repo, never from CI.
`

const main = async () => {
    const args = process.argv.slice(2)
    if (args.includes("--help") || args.includes("-h")) {
        console.log(HELP)
        return
    }
    const knownFlags = ["--write-override",
        "--quiet",
        "--help",
        "-h"]
    let explicitOut = null
    const unknown = []
    for (let i = 0; i < args.length; i += 1) {
        const arg = args[i]
        if (arg === "--out") {
            explicitOut = args[i + 1] ?? null
            if (!explicitOut) {
                fail("--out needs a path argument.",
                    ["example: npm run sync -- --out .env.override.preview"])
            }
            i += 1
            continue
        }
        if (arg.startsWith("--out=")) {
            explicitOut = arg.slice("--out=".length)
            continue
        }
        if (!knownFlags.includes(arg)) {
            unknown.push(arg)
        }
    }
    if (unknown.length > 0) {
        fail(`unknown argument(s): ${unknown.join(", ")}`,
            ["run `npm run sync -- --help` for the supported flags."])
    }
    QUIET = args.includes("--quiet")
    const forceOverride = args.includes("--write-override")

    if (!QUIET) {
        console.log(cyan("starci-academy-backend :: sync"))
    }
    const {
        ports
    } = readMetadata()
    const masterKeyPath = locateMasterKey()
    ensureTools()
    const table = await loadCredentialTable()
    // Only `runtime/env` carries KEY=VALUE pairs. `runtime/files` is decrypted to
    // disk for the app to read BY PATH; folding it into the env bridge would
    // inline a whole service-account JSON as an env var.
    const decryptedEnvFiles = decryptDevStack(masterKeyPath)
        .filter((file) => file.startsWith(PATHS.stacksDevRuntimeEnv)
            && file.endsWith(".env"))
    const credentials = readCredentialValues(table)
    const dataMountPath = gitmountPath("data")
    const target = resolveTarget(explicitOut,
        forceOverride)
    const {
        emitted
    } = writeEnvBridge(ports,
        decryptedEnvFiles,
        credentials,
        dataMountPath,
        target)
    // Skipped under --quiet: this clones/pulls over the network, and the prestart
    // hook must not turn `npm run start:dev` into a network-dependent command.
    if (!QUIET) {
        syncGitmounts(credentials)
    }
    ensureRuntimeFiles(table,
        dataMountPath)
    crossCheckKeysDoc(emitted)
    if (!QUIET) {
        printSummary(ports,
            target)
    }
}

main()
