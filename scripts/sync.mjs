const USE_COLOR = Boolean(process.stdout.isTTY) && !process.env.NO_COLOR
const paint = (code, text) => USE_COLOR
    ? `[${code}m${text}[0m`
    : text
const cyan = (text) => paint("36",
    text)
const green = (text) => paint("32",
    text)
const yellow = (text) => paint("33",
    text)
const red = (text) => paint("31",
    text)
const dim = (text) => paint("2",
    text)

let stepNumber = 0

/**
 * Quiet mode. Set by `--quiet`, which is how the npm `prestart` hooks run this
 * script before every `npm run start:dev`. There it must be near-silent, must
 * never touch the network, and must NEVER be fatal -- a machine without sops
 * installed still has to be able to start the dev server it started yesterday.
 */
let QUIET = false

/** Prints a numbered step header. */
const step = (title) => {
    stepNumber += 1
    if (!QUIET) {
        console.log(`\n${cyan(`==> ${stepNumber}. ${title}`)}`)
    }
}

const info = (message) => {
    if (!QUIET) {
        console.log(`    ${message}`)
    }
}
const note = (message) => {
    if (!QUIET) {
        console.log(`    ${dim(message)}`)
    }
}
const ok = (message) => {
    if (!QUIET) {
        console.log(`    ${green("ok")}   ${message}`)
    }
}
const warn = (message) => console.log(`    ${yellow("warn")} ${message}`)

/**
 * Aborts with a readable, actionable message instead of a stack trace.
 *
 * Under `--quiet` it does NOT abort: it prints one warning line and exits 0.
 * The prestart hook must never be the reason `npm run start:dev` fails.
 * @param title - one-line statement of what went wrong.
 * @param remedy - lines telling the operator exactly what to do next.
 */
const fail = (title, remedy = []) => {
    if (QUIET) {
        console.log(`    ${yellow("warn")} sync skipped: ${title}`)
        console.log(`    ${dim("run `npm run sync` for the full explanation")}`)
        process.exit(0)
    }
    console.error(`\n${red(`FAILED: ${title}`)}`)
    for (const line of remedy) {
        console.error(`    ${line}`)
    }
    console.error("")
    process.exit(1)
}

