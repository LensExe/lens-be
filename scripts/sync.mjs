/** Port names this script refuses to run without. */
const REQUIRED_PORTS = ["core",
    "postgres",
    "redis",
    "elasticsearch",
    "qdrant",
    "kafka",
    "minio",
    "nats",
    "keycloak",
    "prometheus"]

/**
 * Reads metadata.json as-is, without the port validation `readMetadata` does.
 * Used by the gitmounts step, which needs a different part of the same file.
 * @returns the parsed object, or `{}` when the file is unreadable.
 */
const readMetadataRaw = () => {
    try {
        return JSON.parse(readFileSync(PATHS.metadata,
            "utf8"))
    } catch {
        return {
        }
    }
}

/**
 * Reads metadata.json and returns the resolved port map. Every port used
 * anywhere below comes from here -- nothing in this script hardcodes one.
 */
const readMetadata = () => {
    step("metadata.json (port source of truth)")
    if (!existsSync(PATHS.metadata)) {
        fail("metadata.json is missing at the repo root.",
            [`expected: ${PATHS.metadata}`,
                "It declares service identities and the resolved \"ports\" projection that",
                "other files (compose fragments, the env bridge) consume.",
                "Restore it from git."])
    }
    let metadata
    try {
        metadata = JSON.parse(readFileSync(PATHS.metadata,
            "utf8"))
    } catch (error) {
        fail("metadata.json is not valid JSON.",
            [`file:  ${PATHS.metadata}`,
                `error: ${error.message}`])
    }
    const ports = metadata.ports ?? {
    }
    const missing = REQUIRED_PORTS.filter((name) => typeof ports[name] !== "number")
    if (missing.length > 0) {
        fail("metadata.json is missing required ports.",
            [`missing: ${missing.join(", ")}`,
                "Add their Source-resolved values under \"ports\" and declare them in \"portServices\"."])
    }
    ok(`project "${metadata.project ?? "unknown"}", ${Object.keys(ports).length} resolved ports`)
    return {
        metadata, ports
    }
}

