/**
 * Resolves an executable against PATH by hand. `spawnSync` without a shell does
 * not honour PATHEXT on Windows, so `sops`/`age`/`git` would look "missing"
 * there even when installed. Resolving to an absolute path keeps `shell: false`
 * (no quoting hazards) while still finding `.exe` / `.cmd` shims.
 * @param command - bare command name, e.g. "sops".
 * @returns absolute path to the executable, or null when not found.
 */
const resolveCommand = (command) => {
    const searchDirs = (process.env.PATH || "").split(delimiter).filter(Boolean)
    if (IS_WINDOWS && process.env.LOCALAPPDATA) {
        // winget puts its shims here and the PATH entry only lands in NEW shells
        const wingetRoot = join(process.env.LOCALAPPDATA,
            "Microsoft",
            "WinGet")
        searchDirs.push(join(wingetRoot,
            "Links"))
        // Not every package gets a Links shim -- age and sops both install as a
        // bare exe under Packages/<id>/ (sometimes one level deeper) and rely on
        // a PATH entry this process is too old to have seen. Walk it directly.
        const packagesRoot = join(wingetRoot,
            "Packages")
        if (existsSync(packagesRoot)) {
            for (const entry of readdirSync(packagesRoot)) {
                const packageDir = join(packagesRoot,
                    entry)
                searchDirs.push(packageDir)
                try {
                    for (const nested of readdirSync(packageDir,
                        {
                            withFileTypes: true
                        })) {
                        if (nested.isDirectory()) {
                            searchDirs.push(join(packageDir,
                                nested.name))
                        }
                    }
                } catch {
                    // unreadable package dir -- skip, another candidate may match
                }
            }
        }
    }
    const extensions = IS_WINDOWS
        ? (process.env.PATHEXT || ".EXE;.CMD;.BAT").split(";").filter(Boolean)
        : [""]
    for (const dir of searchDirs) {
        for (const extension of extensions) {
            const candidate = join(dir,
                `${command}${extension}`)
            if (existsSync(candidate)) {
                return candidate
            }
        }
    }
    return null
}

/**
 * Runs a command and returns its result. Never throws.
 * @param command - bare command name (resolved via resolveCommand).
 * @param args - argument list.
 * @param options - `{ cwd, env, capture }`; `capture: false` inherits stdio.
 */
const run = (command, args, options = {
}) => {
    const executable = resolveCommand(command)
    if (!executable) {
        return {
            found: false, status: -1, stdout: "", stderr: ""
        }
    }
    const result = spawnSync(executable,
        args,
        {
            cwd: options.cwd ?? REPO_ROOT,
            env: options.env ?? process.env,
            encoding: "utf8",
            stdio: options.capture === false ? "inherit" : "pipe",
        })
    return {
        found: true,
        status: result.status ?? -1,
        stdout: result.stdout ?? "",
        stderr: result.stderr ?? "",
    }
}

