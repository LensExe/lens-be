// step 5 -- generate the env bridge
// ---------------------------------------------------------------------------

/**
 * Extracts every env key `src/modules/platform/env/config.ts` actually reads, so
 * this script can never emit a key the app ignores. Handles both literal keys
 * (`key: "CORE_PORT"`) and templated ones (`key: NATS_SERVER_${i + 1}_HOST`).
 * @returns `{ literal: Set<string>, patterns: RegExp[] }`
 */
const collectConfigKeys = () => {
    if (!existsSync(PATHS.config)) {
        fail("src/modules/platform/env/config.ts is missing.",
            [`expected: ${PATHS.config}`,
                "It is the only list of env keys the app reads; without it this script",
                "cannot tell a real key from a typo."])
    }
    const body = readFileSync(PATHS.config,
        "utf8")
    const literal = new Set()
    for (const match of body.matchAll(/key:\s*"([A-Za-z0-9_.]+)"/g)) {
        literal.add(match[1])
    }
    const patterns = []
    for (const match of body.matchAll(/key:\s*`([^`]+)`/g)) {
        // every templated family in config.ts is indexed by a number (`${i + 1}`),
        // so the placeholder becomes \d+ -- narrow on purpose, otherwise the
        // doc placeholders in KEYS.md ("NATS_SERVER_N_HOST") read as real keys
        const source = match[1]
            .replace(/[.*+?^${}()|[\]\\]/g,
                "\\$&")
            .replace(/\\\$\\\{[^}]*\\\}/g,
                "\\d+")
        patterns.push(new RegExp(`^${source}$`))
    }
    return {
        literal, patterns
    }
}

/**
 * Finds every key in config.ts whose default is `join(process.cwd(), ...)` and
 * returns the literal path segments of that default.
 *
 * This is how the mount-path overrides stay honest: the relocation table below
 * is driven by what config.ts ACTUALLY declares, so a credential added to
 * config.ts later is picked up without editing this script.
 * @returns array of `{ key, segments }`.
 */
const collectMountPathDefaults = () => {
    const body = readFileSync(PATHS.config,
        "utf8")
    const found = []
    const keyPattern = /key:\s*"([A-Za-z0-9_.]+)"/g
    let match = keyPattern.exec(body)
    while (match !== null) {
        const key = match[1]
        // window starts AFTER this key so the scan below cannot borrow it
        const window = body.slice(match.index + match[0].length,
            match.index + match[0].length + 400)
        const joinAt = window.search(/defaultValue:\s*join\(/)
        // a `key:` between here and the join means the join belongs to the NEXT
        // entry, not this one -- skip rather than mis-attribute a path
        const stolen = joinAt !== -1 && /key:\s*["`]/.test(window.slice(0,
            joinAt))
        if (joinAt !== -1 && !stolen) {
            const openParen = window.indexOf("(",
                window.indexOf("join",
                    joinAt))
            // balance-scan to the matching ")" -- `process.cwd()` nests one level
            let depth = 0
            let end = -1
            for (let i = openParen; i < window.length; i += 1) {
                if (window[i] === "(") {
                    depth += 1
                } else if (window[i] === ")") {
                    depth -= 1
                    if (depth === 0) {
                        end = i
                        break
                    }
                }
            }
            if (end !== -1) {
                const argumentList = window.slice(openParen + 1,
                    end)
                const segments = [...argumentList.matchAll(/"([^"]*)"/g)]
                    .map((segment) => segment[1])
                if (segments.length > 0) {
                    found.push({
                        key, segments
                    })
                }
            }
        }
        match = keyPattern.exec(body)
    }
    return found
}

/**
 * Relocates one legacy `.mount/...` default onto the new tree.
 *
 *   .mount/terraform/<name>          -> .stacks/dev/runtime/files/<name>
 *   .mount/terraform/keys[/<name>]   -> .stacks/dev/runtime/files[/<name>]
 *   .mount/config/app.yaml           -> .stacks/dev/runtime/files/app.yaml
 *   .mount/config/seed.yaml          -> .stacks/dev/runtime/config/seed.yaml
 *   .mount/data/<rest...>            -> <gitmount path>/<rest...>
 *   .mount/assets                    -> <gitmount path>/assets
 *
 * The assets rule is not a guess. `.mount/assets` used to hold ten foundation
 * logos while the data repo carried the same ten under `assets/foundation`
 * alongside the achievement badges and course covers -- and AssetsService
 * uploads its whole root under the `assets/` object-key prefix, which is where
 * `assets/badges/achievements/*.png` has to come from. The mount was the cut-down
 * copy; the gitmount is the real root.
 *
 * Everything else is left alone on purpose:
 *   - `.mount/config/metadata.json` is i18n CONTENT rather than a secret. Note
 *     that nothing reads it: `CONFIG_METADATA_MOUNT_PATH` is declared in
 *     config.ts and consumed nowhere, so relocating it would move a dead file;
 *   - defaults that do not start at `.mount` (e.g. `.contexts`) are not ours.
 * @param segments - the literal path segments of the config.ts default.
 * @param dataMountPath - repo-relative POSIX path of the `data` gitmount.
 * @returns the replacement POSIX path, or null when the default stays as it is.
 */
const relocateMountPath = (segments, dataMountPath) => {
    if (segments[0] !== ".mount") {
        return null
    }
    const rest = segments.slice(1)
    if (rest[0] === "terraform") {
        // the AI key pools are flattened into runtime/files beside everything else
        const tail = rest[1] === "keys" ? rest.slice(2) : rest.slice(1)
        return [RUNTIME_FILES_PREFIX,
            ...tail].join("/")
    }
    if (rest[0] === "config") {
        if (rest[1] === "app.yaml") {
            return `${RUNTIME_FILES_PREFIX}/app.yaml`
        }
        if (rest[1] === "seed.yaml") {
            return `${RUNTIME_CONFIG_PREFIX}/seed.yaml`
        }
        return null
    }
    if (rest[0] === "data") {
        return [dataMountPath,
            ...rest.slice(1)].join("/")
    }
    if (rest[0] === "assets") {
        return [dataMountPath,
            ...rest].join("/")
    }
    return null
}

