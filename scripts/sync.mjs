/**
 * Decides WHERE the env bridge is written, and why.
 *
 * The whole point of this function is that a normal `npm run sync` on a machine
 * whose `.env.override` was written by hand must not touch that file. See the
 * header block for the promotion sequence.
 * @param explicitOut - value of `--out`, or null.
 * @param forceOverride - true when `--write-override` was passed.
 */
const resolveTarget = (explicitOut, forceOverride) => {
    if (explicitOut) {
        return {
            path: resolve(REPO_ROOT,
                explicitOut),
            mode: "explicit",
        }
    }
    if (forceOverride) {
        return {
            path: PATHS.envOverride, mode: "forced"
        }
    }
    if (!existsSync(PATHS.envOverride)) {
        return {
            path: PATHS.envOverride, mode: "fresh"
        }
    }
    const head = readFileSync(PATHS.envOverride,
        "utf8").slice(0,
        GENERATED_MARKER.length)
    if (head === GENERATED_MARKER) {
        return {
            path: PATHS.envOverride, mode: "regenerate"
        }
    }
    return {
        path: PATHS.envPreview, mode: "preview"
    }
}

/**
 * Writes the env bridge -- the file that reconciles config.ts standard-port,
 * `.mount`-rooted defaults with the offset ports compose publishes and the
 * credentials that now live under `.stacks/dev/runtime`.
 * @param ports - resolved port map.
 * @param decryptedEnvFiles - plaintext `.env` paths produced by step 4.
 * @param credentials - `{ pointers, missing }` from readCredentialValues.
 * @param dataMountPath - repo-relative POSIX path of the `data` gitmount.
 * @param target - `{ path, mode }` from resolveTarget.
 * @returns `{ emitted: string[] }` -- names only, never values.
 */
const writeEnvBridge = (
    ports,
    decryptedEnvFiles,
    credentials,
    dataMountPath,
    target,
) => {
    step("generate the env bridge")
    const {
        literal, patterns
    } = collectConfigKeys()
    const isKnownKey = (key) => literal.has(key)
        || patterns.some((pattern) => pattern.test(key))
    note(`config.ts declares ${literal.size} literal keys + ${patterns.length} templated keys`)

    // decrypted env files first, so a real stored value beats the shaped default
    const fromSecrets = {
    }
    for (const file of decryptedEnvFiles) {
        Object.assign(fromSecrets,
            parseEnvBody(readFileSync(file,
                "utf8")))
    }
    if (decryptedEnvFiles.length > 0) {
        note(`merged ${Object.keys(fromSecrets).length} keys from ${decryptedEnvFiles.length} decrypted file(s)`)
    }

    const emitted = []
    const skipped = []
    const unfilled = []
    const usedFromSecrets = new Set()

    const lines = [`${GENERATED_MARKER} -- DO NOT EDIT BY HAND`,
        "#",
        "# Every edit here is overwritten by the next `npm run sync`. Change the source",
        "# instead:",
        "#   ports        -> metadata.json  (resolved from Source-owned allocation)",
        "#   credentials  -> .stacks/dev/runtime/**  (sops, then `npm run sync`)",
        "#",
        "# Why this file exists: src/modules/platform/env/config.ts defaults to STANDARD",
        "# ports (postgres 5432, redis 6379, qdrant 6333) and to the legacy `.mount` tree,",
        "# while the compose fragments publish OFFSET ports and the credentials live under",
        "# `.stacks/dev/runtime`. @nestjs/config gives the FIRST file that defines a key",
        "# priority, so a stale `.env.local` silently beats everything generated here.",
        "# Delete it if unsure.",
        "#",
        `# generated: ${new Date().toISOString()}`,
        ""]

    for (const section of buildDerivedSections(ports)) {
        const sectionLines = []
        for (const [key, derivedValue] of section.entries) {
            if (!isKnownKey(key)) {
                skipped.push(key)
                continue
            }
            // `null` marks a generated credential: it only ever comes off disk,
            // and it goes over as a `<KEY>_FILE` pointer rather than a value.
            // Never fall back to the config.ts default here -- that default is
            // the OLD password and would authenticate against nothing.
            if (derivedValue === null) {
                if (!credentials.pointers.has(key)) {
                    unfilled.push(key)
                    continue
                }
                sectionLines.push(`${key}_FILE=${formatEnvValue(credentials.pointers.get(key))}`)
                emitted.push(key)
                continue
            }
            const overridable = !METADATA_OWNED_KEYS.has(key)
            const hasSecret = Object.prototype.hasOwnProperty.call(fromSecrets,
                key)
            const value = (overridable && hasSecret) ? fromSecrets[key] : derivedValue
            if (overridable && hasSecret) {
                usedFromSecrets.add(key)
            }
            sectionLines.push(`${key}=${formatEnvValue(value)}`)
            emitted.push(key)
        }
        if (sectionLines.length > 0) {
            lines.push(`# ${section.title}`,
                ...sectionLines,
                "")
        }
    }

    // ---- secrets: every credential the sections did not already place, as a
    // `<KEY>_FILE` pointer. This is the whole third-party half of the table --
    // stripe, paypal, github, the AI pools -- which config.ts now reads through
    // `parseEnvSecret` by VALUE key, so the bridge names the file and the app
    // opens it.
    const secretLines = []
    for (const [key, pointer] of [...credentials.pointers.entries()].sort()) {
        if (emitted.includes(key) || !isKnownKey(key)) {
            continue
        }
        secretLines.push(`${key}_FILE=${formatEnvValue(pointer)}`)
        emitted.push(key)
    }
    if (secretLines.length > 0) {
        lines.push("# Secrets -- `<KEY>_FILE` pointers, never values. The app reads the",
            "# file itself in parseEnvSecret (src/modules/platform/env/utils/parse-env.ts).",
            ...secretLines,
            "")
    }

    // ---- mount paths: point the app at .stacks / .gitmounts instead of .mount
    const mountLines = []
    const mountSkipped = []
    for (const {
        key, segments
    } of collectMountPathDefaults()) {
        if (segments[0] !== ".mount" || !isKnownKey(key)) {
            continue
        }
        const relocated = relocateMountPath(segments,
            dataMountPath)
        if (relocated === null) {
            mountSkipped.push(key)
            continue
        }
        // a decrypted env file may still pin a path explicitly (e.g. a shared
        // machine keeps a pool somewhere else) -- that wins over the relocation
        const hasSecret = Object.prototype.hasOwnProperty.call(fromSecrets,
            key)
        if (hasSecret) {
            usedFromSecrets.add(key)
        }
        mountLines.push(`${key}=${formatEnvValue(hasSecret ? fromSecrets[key] : relocated)}`)
        emitted.push(key)
    }
    if (mountLines.length > 0) {
        lines.push("# Mount paths -- the app reads credentials and content from the new tree.",
            "# Relative to the repo root (= process.cwd() when npm scripts run).",
            ...mountLines.sort(),
            "")
    }
    if (mountSkipped.length > 0) {
        note(`${mountSkipped.length} .mount default(s) left as they are (not relocated by the plan): ${mountSkipped.sort().join(", ")}`)
    }

    // anything the decrypted env files carry that the sections did not cover
    const extras = Object.keys(fromSecrets)
        .filter((key) => !emitted.includes(key))
        .sort()
    const extrasKnown = extras.filter((key) => isKnownKey(key))
    for (const key of extras) {
        if (!isKnownKey(key)) {
            skipped.push(key)
        }
    }
    if (extrasKnown.length > 0) {
        lines.push("# From .stacks/dev/runtime/env -- keys not derived from metadata.json")
        for (const key of extrasKnown) {
            lines.push(`${key}=${formatEnvValue(fromSecrets[key])}`)
            emitted.push(key)
        }
        lines.push("")
    }

    // never clobber a hand-written file without leaving a copy behind
    if (target.mode === "forced" && existsSync(PATHS.envOverride)) {
        const existing = readFileSync(PATHS.envOverride,
            "utf8")
        if (!existing.startsWith(GENERATED_MARKER)) {
            copyFileSync(PATHS.envOverride,
                PATHS.envOverrideBackup)
            warn("the existing .env.override was NOT generated by this script.")
            warn(`backed it up to ${basename(PATHS.envOverrideBackup)} before overwriting.`)
            warn("that backup is gitignored but still holds real credentials in plaintext --")
            warn("fold anything you still need into .stacks/dev/runtime, then delete it.")
        }
    }

    mkdirSync(dirname(target.path),
        {
            recursive: true
        })
    writeFileSync(target.path,
        lines.join("\n"),
        "utf8")
    const label = relative(REPO_ROOT,
        target.path).split(sep).join("/")
    ok(`wrote ${label} -- ${emitted.length} keys`)
    if (target.mode === "preview") {
        note("the live .env.override was NOT touched: it is hand-written, so this run")
        note("produced a preview instead. Diff the two by key name, then promote with")
        note("`npm run sync -- --write-override` once the new stack is up.")
    }
    if (usedFromSecrets.size > 0) {
        note(`${usedFromSecrets.size} value(s) came from the decrypted stack: ${[...usedFromSecrets].sort().join(", ")}`)
    }
    if (unfilled.length > 0) {
        warn(`${unfilled.length} generated credential(s) have no file yet, so the key was NOT emitted:`)
        for (const key of unfilled.sort()) {
            console.log(`      - ${key}`)
        }
        note("mint them with `npm run secret:gen`, then re-run `npm run sync`.")
    }
    if (credentials.missing.length > 0) {
        note(`credential files still missing under .stacks/dev/runtime/files: ${credentials.missing.sort().join(", ")}`)
    }
    if (skipped.length > 0) {
        warn(`skipped ${skipped.length} key(s) config.ts does not read: ${[...new Set(skipped)].sort().join(", ")}`)
    }
    return {
        emitted
    }
}

