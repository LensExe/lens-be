/**
 * Returns the repo-relative POSIX path of a declared gitmount.
 * @param name - the gitmount key in metadata.json.
 */
const gitmountPath = (name) => {
    const declared = readMetadataRaw().gitmounts ?? {
    }
    const mount = declared[name]
    return (mount && mount.path) ? mount.path : `.gitmounts/${name}`
}

/**
 * Builds a non-interactive Git environment for one mount. A declared token is
 * read from its already decrypted runtime file and passed to Git through a
 * process-only config entry. It is never persisted in the remote URL, Git
 * config, generated env bridge, or command line.
 * @param mount - one metadata.json gitmount declaration.
 * @param credentials - `{ pointers }` from readCredentialValues.
 * @returns `{ env, authenticated }`.
 */
const gitmountEnvironment = (mount, credentials) => {
    const env = {
        ...process.env,
        GIT_TERMINAL_PROMPT: "0",
    }
    const names = [mount.credentialEnv,
        ...(Array.isArray(mount.credentialFallbackEnvs)
            ? mount.credentialFallbackEnvs
            : [])].filter((name) => typeof name === "string" && name !== "")
    const credentialName = names.find((name) => credentials.pointers.has(name))
    if (!credentialName) {
        return {
            env, authenticated: false
        }
    }
    const pointer = credentials.pointers.get(credentialName)
    const tokenPath = join(REPO_ROOT,
        pointer.split("/").join(sep))
    const token = readFileSync(tokenPath,
        "utf8").trim()
    if (token === "") {
        return {
            env, authenticated: false
        }
    }
    let origin
    try {
        origin = new URL(mount.repo).origin
    } catch {
        return {
            env, authenticated: false
        }
    }
    const parsedCount = Number.parseInt(env.GIT_CONFIG_COUNT ?? "0",
        10)
    const configIndex = Number.isSafeInteger(parsedCount) && parsedCount >= 0
        ? parsedCount
        : 0
    env.GIT_CONFIG_COUNT = String(configIndex + 1)
    env[`GIT_CONFIG_KEY_${configIndex}`] = `http.${origin}/.extraheader`
    env[`GIT_CONFIG_VALUE_${configIndex}`] = `Authorization: Basic ${Buffer.from(`x-access-token:${token}`,
        "utf8").toString("base64")}`
    return {
        env, authenticated: true
    }
}

/**
 * Clones or refreshes every gitmount declared in metadata.json. For this repo
 * that is the private seed-content repo that used to live at `.mount/data`.
 * @param credentials - `{ pointers }` from readCredentialValues.
 */
const syncGitmounts = (credentials) => {
    step(".gitmounts")
    const declared = readMetadataRaw().gitmounts
    if (!declared || Object.keys(declared).length === 0) {
        note("metadata.json declares no gitmounts -- nothing to fetch.")
        return
    }
    if (resolveCommand("git") === null) {
        fail("git is not on PATH.",
            ["every .gitmounts entry is a clone of a git repository.",
                "Install git, then re-run `npm run sync`."])
    }
    for (const [name, mount] of Object.entries(declared)) {
        const auth = gitmountEnvironment(mount,
            credentials)
        const label = mount.path || `.gitmounts/${name}`
        const target = join(REPO_ROOT,
            label.split("/").join(sep))
        if (existsSync(join(target,
            ".git"))) {
            const result = run("git",
                ["-C",
                    target,
                    "pull",
                    "--ff-only"],
                {
                    env: auth.env
                })
            if (result.status === 0) {
                ok(`${label} -- ${result.stdout.trim().split(/\r?\n/).pop() || "up to date"}`)
            } else {
                // offline or a dirty working copy is annoying, not fatal
                warn(`could not pull ${label}; keeping the checkout already there.`)
                warn(result.stderr.trim().split(/\r?\n/).pop() ?? "")
            }
            continue
        }
        info(`cloning ${mount.repo} -> ${label}`)
        const args = ["clone",
            "--quiet"]
        if (mount.ref) {
            args.push("--branch",
                mount.ref)
        }
        args.push(mount.repo,
            target)
        const result = run("git",
            args,
            {
                env: auth.env
            })
        if (result.status !== 0) {
            fail(`could not clone ${mount.repo} into ${label}`,
                [result.stderr.trim().split(/\r?\n/).slice(-3).join("\n    "),
                    "",
                    auth.authenticated
                        ? "The encrypted Git credential was supplied but GitHub rejected or could not use it."
                        : "It may be a PRIVATE repo and no declared encrypted Git credential was available.",
                    "Check the mount credential declaration and encrypted runtime file,",
                    "then re-run `npm run sync`."])
        }
        ok(`${label} cloned`)
    }
}

// ---------------------------------------------------------------------------
// step 7 -- placeholders so boot never ENOENTs
// ---------------------------------------------------------------------------

/**
 * Creates an empty placeholder for every `*.key` the app will read out of
 * `.stacks/dev/runtime/files` but that is not there.
 *
 * The app calls `readFileSync` on these at boot and dies with ENOENT when one is
 * absent -- it has no concept of "this provider is not configured". The old
 * `.mount/terraform` tree papered over that by shipping empty `.key` files; that
 * job moves here. An empty file means what it meant before: the feature behind
 * it is unavailable locally.
 *
 * Structured credentials (`*.json`, `*.yaml`) are deliberately NOT placeheld: an
 * empty one crashes the parser instead of the reader, which is a worse error
 * than the honest ENOENT. Those must come from the migration, so they are
 * reported by name instead.
 * @param table - the loaded credential table (extra filenames, if any).
 * @param dataMountPath - repo-relative POSIX path of the `data` gitmount.
 */
const ensureRuntimeFiles = (table, dataMountPath) => {
    step("runtime placeholders")
    for (const dir of [PATHS.stacksDevRuntimeFiles,
        PATHS.stacksDevRuntimeEnv,
        PATHS.stacksDevRuntimeConfig]) {
        mkdirSync(dir,
            {
                recursive: true
            })
    }

    const wanted = new Set()
    for (const {
        segments
    } of collectMountPathDefaults()) {
        const relocated = relocateMountPath(segments,
            dataMountPath)
        if (relocated === null || !relocated.startsWith(`${RUNTIME_FILES_PREFIX}/`)) {
            continue
        }
        wanted.add(relocated.slice(RUNTIME_FILES_PREFIX.length + 1))
    }
    for (const credential of table.APP_CREDENTIALS) {
        if (credential && typeof credential.file === "string") {
            wanted.add(credential.file)
        }
    }

    const created = []
    const structuredMissing = []
    for (const name of [...wanted].sort()) {
        const target = join(PATHS.stacksDevRuntimeFiles,
            name.split("/").join(sep))
        if (existsSync(target)) {
            continue
        }
        if (!name.endsWith(".key")) {
            structuredMissing.push(name)
            continue
        }
        mkdirSync(dirname(target),
            {
                recursive: true
            })
        writeFileSync(target,
            "",
            "utf8")
        created.push(name)
    }
    if (created.length > 0) {
        note(`created ${created.length} empty placeholder(s) so boot does not ENOENT: ${created.join(", ")}`)
    }
    if (structuredMissing.length > 0) {
        warn(`structured credential file(s) absent -- run the migration, they are NOT placeheld: ${structuredMissing.join(", ")}`)
    }

    // seed.yaml is per-machine dev state, not a secret: it comes from a template
    const seedTarget = join(PATHS.stacksDevRuntimeConfig,
        "seed.yaml")
    if (!existsSync(seedTarget)) {
        if (existsSync(PATHS.seedTemplate)) {
            copyFileSync(PATHS.seedTemplate,
                seedTarget)
            ok("seeded .stacks/dev/runtime/config/seed.yaml from config/seed.example.yaml")
        } else {
            warn("no .stacks/dev/runtime/config/seed.yaml and no config/seed.example.yaml to copy.")
            warn("boot will ENOENT on CONFIG_INIT_SCOPE_MOUNT_PATH until one of them exists.")
        }
    }
    if (created.length === 0 && structuredMissing.length === 0) {
        ok("every runtime file the app reads is present")
    }
}

// ---------------------------------------------------------------------------
// step 8 -- KEYS.md cross-check
// ---------------------------------------------------------------------------

/**
 * Reads `.stacks/dev/runtime/env/KEYS.md` -- the human-maintained roster of what
 * the dev stack is supposed to supply -- and reports, BY NAME ONLY, anything it
 * lists that the generated env bridge did not end up carrying.
 * @param emitted - key names written in step 5.
 */
const crossCheckKeysDoc = (emitted) => {
    step("cross-check KEYS.md")
    const keysDoc = join(PATHS.stacksDevRuntimeEnv,
        "KEYS.md")
    if (!existsSync(keysDoc)) {
        note("no .stacks/dev/runtime/env/KEYS.md -- nothing to cross-check.")
        return
    }
    const {
        literal, patterns
    } = collectConfigKeys()
    const isKnownKey = (key) => literal.has(key)
        || patterns.some((pattern) => pattern.test(key))
    const body = readFileSync(keysDoc,
        "utf8")

    // KEYS.md is a set of markdown tables with a "required" column. Read each row
    // as: the SHOUTING_TOKENS it names, plus whether any cell says "optional".
    // Tokens are then filtered against config.ts, which drops the prose and the
    // placeholder rows ("REDIS_<LANE>_HOST") without needing to parse them.
    const documented = new Map()
    for (const line of body.split(/\r?\n/)) {
        if (!line.trim().startsWith("|")) {
            continue
        }
        const isOptional = /\boptional\b/i.test(line)
        for (const match of line.matchAll(/\b[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+\b/g)) {
            const key = match[0]
            if (!isKnownKey(key)) {
                continue
            }
            // a key listed required anywhere stays required
            documented.set(key,
                documented.get(key) === true || !isOptional)
        }
    }
    if (documented.size === 0) {
        note("KEYS.md lists no key that config.ts reads -- nothing to compare.")
        return
    }
    const emittedSet = new Set(emitted)
    const missingRequired = [...documented.entries()]
        .filter(([key, required]) => required && !emittedSet.has(key))
        .map(([key]) => key)
        .sort()
    const missingOptional = [...documented.entries()]
        .filter(([key, required]) => !required && !emittedSet.has(key))
        .map(([key]) => key)
        .sort()

    note(`KEYS.md documents ${documented.size} key(s) config.ts reads`)
    if (missingRequired.length === 0) {
        ok("every REQUIRED documented key is present in the generated env bridge")
    } else {
        warn(`${missingRequired.length} REQUIRED key(s) documented in KEYS.md are MISSING:`)
        for (const key of missingRequired) {
            console.log(`      - ${key}`)
        }
        note("supply them via .stacks/dev/runtime/env/*.env.enc and re-run, or mark them")
        note("optional in KEYS.md if the config.ts default is genuinely good enough.")
    }
    if (missingOptional.length > 0) {
        const shown = missingOptional.slice(0,
            12).join(", ")
        const rest = missingOptional.length > 12
            ? `, +${missingOptional.length - 12} more`
            : ""
        note(`${missingOptional.length} optional key(s) not emitted (config.ts defaults apply): ${shown}${rest}`)
    }
}

