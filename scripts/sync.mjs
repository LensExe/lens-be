/** Per-platform install hints. Nothing is ever installed silently. */
const INSTALL_HINTS = {
    sops: {
        win32: "winget install Mozilla.SOPS",
        darwin: "brew install sops",
        linux: "curl -sSLo sops https://github.com/getsops/sops/releases/latest/download/sops-linux-amd64 && sudo install -m 0755 sops /usr/local/bin/sops",
    },
    age: {
        win32: "winget install FiloSottile.age",
        darwin: "brew install age",
        linux: "sudo apt-get install -y age",
    },
}

/** Fails unless both `sops` and `age` are callable. */
const ensureTools = () => {
    step("sops + age")
    const current = platform()
    const missing = ["sops",
        "age"].filter((tool) => resolveCommand(tool) === null)
    if (missing.length > 0) {
        const width = Math.max(...missing.map((tool) => tool.length))
        const hints = missing.map((tool) => {
            const hint = INSTALL_HINTS[tool][current] ?? INSTALL_HINTS[tool].linux
            return `  ${`${tool}:`.padEnd(width + 2)} ${hint}`
        })
        fail(`missing on PATH: ${missing.join(", ")}`,
            ["Install, open a NEW shell so PATH is picked up, then re-run `npm run sync`.",
                "",
                ...hints,
                "",
                "Nothing is installed for you on purpose -- these tools hold the keys to",
                "every secret in the repo, so you choose where they come from."])
    }
    const sopsVersion = run("sops",
        ["--version"]).stdout.trim().split(/\r?\n/)[0]
    ok(`sops (${sopsVersion || "version unknown"}) and age both on PATH`)
}

// ---------------------------------------------------------------------------
// step 4 -- decrypt .stacks/dev
// ---------------------------------------------------------------------------

/**
 * Walks a directory tree and returns every `*.enc` file in it.
 * @param root - directory to walk; a missing directory yields nothing.
 * @returns absolute paths, sorted so output is stable between runs.
 */
const findEncryptedFiles = (root) => {
    if (!existsSync(root)) {
        return []
    }
    const found = []
    const walk = (dir) => {
        for (const entry of readdirSync(dir,
            {
                withFileTypes: true
            })) {
            const full = join(dir,
                entry.name)
            if (entry.isDirectory()) {
                walk(full)
            } else if (entry.name.endsWith(".enc")) {
                found.push(full)
            }
        }
    }
    walk(root)
    return found.sort()
}

/**
 * Picks the sops format for a file. `.env` files are dotenv; whole-file
 * credentials (api keys, tokens, service-account json) are opaque and must be
 * binary, or sops tries to parse a bare token as JSON and dies.
 * @param plaintextPath - the path without the `.enc` suffix.
 */
const sopsFormatFor = (plaintextPath) => {
    if (plaintextPath.endsWith(".env")) {
        return "dotenv"
    }
    // Never let sops infer. The file it is handed ends in `.enc`, so inference
    // falls back to binary and a JSON secret fails with "No binary data found
    // in tree" -- after encrypting perfectly well, which makes it look like the
    // key is wrong rather than the format.
    if (/\.json$/.test(plaintextPath)) {
        return "json"
    }
    if (/\.ya?ml$/.test(plaintextPath)) {
        return "yaml"
    }
    return "binary"
}

/**
 * Decrypts the whole `dev` stack -- `runtime/env` (folded into the env bridge)
 * and `runtime/files` (whole-file credentials the app reads by path). Only `dev`
 * keeps values on disk: `vps` reads GitHub Actions secrets and `k8s` will read a
 * cloud secret manager, so both are markdown-only scaffolds.
 * @param masterKeyPath - absolute path to the age key sops decrypts with.
 * @returns the decrypted plaintext paths that were produced.
 */
const decryptDevStack = (masterKeyPath) => {
    step("decrypt .stacks/dev")
    if (!existsSync(PATHS.stacksDev)) {
        note(".stacks/dev does not exist yet -- skipping decryption.")
        note("(the env bridge below is still generated from metadata.json)")
        return []
    }
    const encrypted = findEncryptedFiles(PATHS.stacksDev)
    if (encrypted.length === 0) {
        note("no *.enc files found -- nothing to decrypt.")
        return []
    }
    const sopsEnv = {
        ...process.env, SOPS_AGE_KEY_FILE: masterKeyPath
    }
    const produced = []
    for (const source of encrypted) {
        const target = source.replace(/\.enc$/,
            "")
        // The types must be stated. sops infers format from the extension, and
        // `.enc` means nothing to it, so it falls back to JSON and dies on the
        // first comment line: "invalid character '#' looking for beginning of
        // value". Likewise always use --output, never shell redirection: on
        // Windows that writes CRLF and sops then fails to parse its own
        // timestamp ("extra text: \r").
        const format = sopsFormatFor(target)
        const result = run("sops",
            ["--decrypt",
                "--input-type",
                format,
                "--output-type",
                format,
                "--output",
                target,
                source],
            {
                env: sopsEnv
            })
        const label = relative(PATHS.stacksDev,
            source).split(sep).join("/")
        if (result.status !== 0) {
            fail(`sops could not decrypt ${label}`,
                [`sops exit code ${result.status}`,
                    result.stderr.trim().split(/\r?\n/).slice(-4)
                        .map((line) => `  ${line}`).join("\n"),
                    "",
                    "Usual causes:",
                    "  - the master key is not a recipient of this file (re-encrypt it), or",
                    "  - the file was encrypted with a different key.",
                    `key in use: ${masterKeyPath}`])
        }
        produced.push(target)
        ok(label.replace(/\.enc$/,
            ""))
    }
    return produced
}

